#!/usr/bin/env python3
"""Generates Sources/GrepRegex/UnicodeTables.swift from regex-syntax's tables.

Usage: Scripts/generate_unicode_tables.py /path/to/regex-syntax/src/unicode_tables

ripgrep's regex engine uses these tables (Unicode 16.0.0 in regex-syntax
0.8), so taking them from there, rather than from the Swift standard
library's newer Unicode data, keeps `\\w`, `\\p{...}` and case folding the same
as ripgrep's.
"""

import re
import sys
from pathlib import Path

src = Path(sys.argv[1])

CHAR = r"'((?:\\u\{[0-9a-fA-F]+\}|\\.|[^'\\])+)'"


def char_value(text):
    if text.startswith("\\u{"):
        return int(text[3:-1], 16)
    if text.startswith("\\"):
        return {"\\0": 0, "\\t": 9, "\\n": 10, "\\r": 13, "\\'": 39, '\\"': 34, "\\\\": 92}[text]
    assert len(text) == 1, text
    return ord(text)


def range_tables(name):
    """The `(char, char)` tables of a file, by constant name, and its BY_NAME list."""
    text = (src / f"{name}.rs").read_text()
    tables = {}
    for match in re.finditer(r"pub const (\w+): &'static \[\(char, char\)\] =\s*&\[(.*?)\];", text, re.S):
        pairs = re.findall(r"\(" + CHAR + r",\s*" + CHAR + r"\)", match.group(2))
        tables[match.group(1)] = [(char_value(a), char_value(b)) for a, b in pairs]
    by_name = re.search(r"pub const BY_NAME: [^=]+=\s*&\[(.*?)\];", text, re.S)
    names = re.findall(r'\("([^"]+)",\s*(\w+)\)', by_name.group(1)) if by_name else []
    return tables, names


def string_pairs(text):
    return re.findall(r'\("([^"]*)",\s*"([^"]*)"\)', text)


def emit_ranges(name, ranges, doc):
    lines = [f"  /// {doc}", f"  static let {name}: [UInt32] = ["]
    line = "   "
    for lo, hi in ranges:
        item = f" 0x{lo:X}, 0x{hi:X},"
        if len(line) + len(item) > 110:
            lines.append(line)
            line = "   "
        line += item
    if line.strip():
        lines.append(line)
    lines.append("  ]")
    return "\n".join(lines)


out = [
    "// Generated by Scripts/generate_unicode_tables.py from regex-syntax's",
    "// Unicode 16.0.0 tables, the data ripgrep's regex engine uses. Do not edit.",
    "",
    "enum UnicodeTables {",
]

perl_word, _ = range_tables("perl_word")
general, general_names = range_tables("general_category")
booleans, boolean_names = range_tables("property_bool")
out.append(emit_ranges("perlWord", perl_word["PERL_WORD"], "`\\w`, as start and end pairs."))
out.append(emit_ranges("perlDigit", general["DECIMAL_NUMBER"], "`\\d`: the Decimal_Number category."))
out.append(emit_ranges("perlSpace", booleans["WHITE_SPACE"], "`\\s`: the White_Space property."))

folding = (src / "case_folding_simple.rs").read_text()
pairs = []
for source, targets in re.findall(r"\(" + CHAR + r",\s*&\[([^\]]*)\]\)", folding):
    for target in re.findall(CHAR, targets):
        pairs.append((char_value(source), char_value(target)))
out.append(emit_ranges("caseFoldPairs", pairs,
                       "Simple case folding: every (scalar, equivalent) pair, sorted by scalar."))

# Every named set, flattened into one array of ranges.
sets = []
indexes = {}
for kind, file in [("generalCategories", "general_category"), ("scripts", "script"),
                   ("scriptExtensions", "script_extension"), ("binaryProperties", "property_bool"),
                   ("ages", "age"), ("graphemeClusterBreaks", "grapheme_cluster_break"),
                   ("wordBreaks", "word_break"), ("sentenceBreaks", "sentence_break")]:
    tables, names = range_tables(file)
    entries = []
    for name, const in names:
        ranges = tables[const]
        entries.append((name, len(sets), len(ranges)))
        sets.extend(ranges)
    indexes[kind] = sorted(entries)
out.append(emit_ranges("sets", sets, "The ranges of every named set below, as start and end pairs."))

out.append("""
  /// A named set: its first pair in `sets` and its number of pairs.
  struct NamedSet {
    let name: String
    let start: Int
    let count: Int
  }
""")
for kind, entries in indexes.items():
    out.append(f"  static let {kind}: [NamedSet] = [")
    for name, start, count in entries:
        out.append(f'    NamedSet(name: "{name}", start: {start}, count: {count}),')
    out.append("  ]")

names_text = (src / "property_names.rs").read_text()
out.append("\n  /// Normalized property names and aliases, sorted, with canonical names.")
out.append("  static let propertyNames: [(String, String)] = [")
for alias, canonical in string_pairs(names_text):
    out.append(f'    ("{alias}", "{canonical}"),')
out.append("  ]")

values_text = (src / "property_values.rs").read_text()
out.append("\n  /// For each canonical property (sorted), its normalized value names and")
out.append("  /// aliases, sorted, with canonical value names.")
out.append("  static let propertyValues: [(String, [(String, String)])] = [")
for prop, body in re.findall(r'\(\s*"([^"]+)",\s*&\[(.*?)\],\s*\)', values_text, re.S):
    out.append(f'    ("{prop}", [')
    for alias, canonical in string_pairs(body):
        out.append(f'      ("{alias}", "{canonical}"),')
    out.append("    ]),")
out.append("  ]")
out.append("}")

target = Path(__file__).resolve().parent.parent / "Sources/GrepRegex/UnicodeTables.swift"
target.write_text("\n".join(out) + "\n")
print(f"{len(sets)} ranges in {sum(len(e) for e in indexes.values())} sets, {len(pairs)} case folding pairs")
