#!/usr/bin/env python3
"""Generates Sources/SwiftGrepKit/EncodingTables.swift from encoding_rs.

Usage: Scripts/generate_encodings.py /path/to/encoding_rs/src

The labels are the WHATWG labels encoding_rs knows, minus those of the
"replacement" encoding, which ripgrep rejects. The single-byte tables give
the code point of each byte from 0x80 to 0xFF (0 where unmapped).
"""

import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
lib = (src / "lib.rs").read_text()
data = (src / "data.rs").read_text()


def array(name):
    match = re.search(r"static " + name + r": \[[^\]]+\] = \[(.*?)\];", lib, re.S)
    return [item.strip() for item in match.group(1).split(",") if item.strip()]


labels = [item.strip('"') for item in array("LABELS_SORTED")]
inits = [item.lstrip("&") for item in array("ENCODINGS_IN_LABEL_SORT")]

variants = {}
for match in re.finditer(r'pub static (\w+_INIT): Encoding = Encoding \{\s*name: "([^"]+)",\s*variant: ([^\n]+)\n', lib):
    variants[match.group(1)] = (match.group(2), match.group(3).rstrip(","))

tables = {}
block = re.search(r"pub static SINGLE_BYTE_DATA: SingleByteData = SingleByteData \{(.*?)\n\};", data, re.S).group(1)
for match in re.finditer(r"(\w+): \[(.*?)\]", block, re.S):
    values = [int(v, 16) for v in re.findall(r"0x[0-9A-Fa-f]+", match.group(2))]
    assert len(values) == 128, match.group(1)
    tables[match.group(1)] = values

order = list(tables)
cases = {
    "Utf8": ".utf8", "Utf16Le": ".utf16LE", "Utf16Be": ".utf16BE", "UserDefined": ".userDefined",
    "Big5": ".big5", "EucJp": ".eucJP", "EucKr": ".eucKR", "Gbk": ".gbk", "Gb18030": ".gb18030",
    "Iso2022Jp": ".iso2022JP", "ShiftJis": ".shiftJIS",
}


def case(init):
    _, variant = variants[init]
    single = re.match(r"VariantEncoding::SingleByte\(&data::SINGLE_BYTE_DATA\.(\w+)", variant)
    if single:
        return f".singleByte({order.index(single.group(1))})"
    kind = re.match(r"VariantEncoding::(\w+)", variant).group(1)
    if kind == "Replacement":
        return None
    return cases[kind]


entries = []
for label, init in zip(labels, inits):
    value = case(init)
    if value:
        entries.append(f'    "{label}": {value},')

rows = []
for name in order:
    values = tables[name]
    rows.append(f"    // {name}")
    for i in range(0, 128, 12):
        rows.append("    " + ", ".join(f"0x{v:04X}" for v in values[i:i + 12]) + ",")

out = f"""// Generated by Scripts/generate_encodings.py from encoding_rs. Do not edit.

extension Encodings {{
  /// The WHATWG labels encoding_rs knows, except those of its "replacement"
  /// encoding, which ripgrep rejects.
  static let byLabel: [String: TextEncoding] = [
{chr(10).join(entries)}
  ]

  /// The code points of bytes 0x80 to 0xFF in each single-byte encoding,
  /// 128 per encoding; 0 means the byte is unmapped.
  static let singleByteTables: [UInt16] = [
{chr(10).join(rows)}
  ]
}}
"""
Path(__file__).resolve().parent.parent.joinpath("Sources/SwiftGrepKit/EncodingTables.swift").write_text(out)
print(f"{len(entries)} labels, {len(order)} single-byte tables")
