// Generates Sources/GrepRegex/UnicodeTables.swift from the Unicode data that
// ships with the Swift standard library.
//
// Usage: swift Scripts/GenerateUnicodeTables.swift > Sources/GrepRegex/UnicodeTables.swift

func ranges(where predicate: (Unicode.Scalar) -> Bool) -> [(UInt32, UInt32)] {
  var result: [(UInt32, UInt32)] = []
  var start: UInt32? = nil
  var value: UInt32 = 0
  while value <= 0x10FFFF {
    let included = Unicode.Scalar(value).map(predicate) ?? false
    if included {
      if start == nil { start = value }
    } else if let s = start {
      result.append((s, value - 1))
      start = nil
    }
    value += 1
  }
  if let s = start { result.append((s, 0x10FFFF)) }
  return result
}

func emit(_ name: String, _ ranges: [(UInt32, UInt32)]) {
  print("  static let \(name): [UInt32] = [")
  var line = "   "
  for (lo, hi) in ranges {
    let item = " 0x\(String(lo, radix: 16, uppercase: true)), 0x\(String(hi, radix: 16, uppercase: true)),"
    if line.count + item.count > 100 {
      print(line)
      line = "   "
    }
    line += item
  }
  if line != "   " { print(line) }
  print("  ]")
}

